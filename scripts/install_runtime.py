"""Apply the public overlay and generate a local stdio-only launcher."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--destination', type=Path, required=True)
    parser.add_argument('--exclude-tools', default='PowerShell,Registry,FileSystem,Process,Scrape')
    args = parser.parse_args()
    source, dest = args.source.resolve(), args.destination.resolve()
    if not (dest / '.kuding-desktop-mcp').is_file():
        raise SystemExit('Installation marker missing.')
    site = dest / 'venv/Lib/site-packages/windows_mcp'
    if not site.is_dir():
        raise SystemExit('Install the pinned upstream distribution first.')
    manifest = json.loads((source / 'public-source-manifest.json').read_text(encoding='utf-8'))
    for entry in manifest['patches']:
        original = (source / entry['path']).resolve()
        original.relative_to(source / 'pkg/patch/windows_mcp')
        if hashlib.sha256(original.read_bytes()).hexdigest() != entry['sha256']:
            raise SystemExit('Source hash mismatch: ' + entry['path'])
        target = site / original.relative_to(source / 'pkg/patch/windows_mcp')
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(original, target)
    # Invalidate only generated bytecode inside this isolated package.
    for cache in site.rglob('__pycache__'):
        cache.resolve().relative_to(site.resolve())
        shutil.rmtree(cache)
    for name in ('VERSION', 'LICENSE', 'THIRD_PARTY_NOTICES.md'):
        shutil.copy2(source / name, dest / name)
    shutil.copy2(source / 'scripts/selftest.py', dest / 'selftest.py')
    shutil.copy2(source / 'scripts/serve.py', dest / 'serve.py')
    shutil.copy2(source / 'public-source-manifest.json', dest / 'public-source-manifest.json')
    shutil.copy2(source / 'pkg/LICENSE-windows-mcp.txt', dest / 'LICENSE-windows-mcp.txt')
    shutil.copytree(source / 'skills', dest / 'skills', dirs_exist_ok=True)
    (dest / 'tool-options.json').write_text(json.dumps({'exclude_tools': args.exclude_tools.split(',') if args.exclude_tools else []}, indent=2), encoding='utf-8')
    # %~dp0 handles spaces and non-ASCII usernames without embedding an
    # installation-specific absolute path in an ASCII batch file.
    launcher = '@echo off\r\n"%~dp0venv\\Scripts\\python.exe" "%~dp0serve.py"\r\n'
    (dest / 'run.cmd').write_bytes(launcher.encode('ascii'))
    config = {'mcpServers': {'kuding-desktop': {'command': str(dest / 'venv/Scripts/python.exe'), 'args': [str(dest / 'serve.py')]}}}
    (dest / 'mcp.json').write_text(json.dumps(config, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Applied and verified {len(manifest["patches"])} overlay files.')


if __name__ == '__main__':
    main()
